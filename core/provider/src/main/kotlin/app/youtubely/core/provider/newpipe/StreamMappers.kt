private const val KBIT = 1000

private fun Int.positiveOrNull(): Int? = takeIf { it > 0 }

private fun mimeType(stream: Stream): String = stream.format?.mimeType ?: "application/octet-stream"

private fun segmentIndex(
    initStart: Int,
    initEnd: Int,
    indexStart: Int,
    indexEnd: Int,
): SegmentIndex? {
    val init = initStart.toLong()..initEnd.toLong()
    val index = indexStart.toLong()..indexEnd.toLong()
    val valid = initStart >= 0 && !init.isEmpty() && index.first > init.last
    return if (valid && !index.isEmpty()) SegmentIndex(init, index) else null
}

/**
 * googlevideo URLs are signed for one InnerTube client; the download must present the same
 * client's User-Agent or the server answers 403.
 */
internal fun mediaHeaders(url: String): Map<String, String> {
    val userAgent =
        when {
            YoutubeParsingHelper.isAndroidStreamingUrl(url) -> YoutubeParsingHelper.getAndroidUserAgent(null)

            YoutubeParsingHelper.isIosStreamingUrl(url) -> YoutubeParsingHelper.getIosUserAgent(null)

            YoutubeParsingHelper.isVisionOsStreamingUrl(url) -> YoutubeParsingHelper.getVisionOsUserAgent(null)

            else -> return mapOf(
                "User-Agent" to NewPipeDownloader.USER_AGENT,
                "Origin" to "https://www.youtube.com",
                "Referer" to "https://www.youtube.com/",
            )
        }
    return mapOf("User-Agent" to userAgent)
}

/** Only directly playable HTTP streams; manifests are exposed separately on [StreamInfo]. */
internal fun NpVideoStream.toVideoStream(): VideoStream? {
    if (!isUrl || deliveryMethod != DeliveryMethod.PROGRESSIVE_HTTP || height <= 0) return null
    return VideoStream(
        url = content,
        mimeType = mimeType(this),
        codecs = codec,
        width = width,
        height = height,
        fps = fps,
        bitrate = bitrate.positiveOrNull(),
        isHdr = getResolution().contains("HDR", ignoreCase = true),
        isVideoOnly = isVideoOnly(),
        segmentIndex = segmentIndex(initStart, initEnd, indexStart, indexEnd),
        contentLength = itagItem?.contentLength?.takeIf { it > 0 },
        httpHeaders = mediaHeaders(content),
    )
}

internal fun NpAudioStream.toAudioStream(): AudioStream? {
    if (!isUrl || deliveryMethod != DeliveryMethod.PROGRESSIVE_HTTP) return null
    return AudioStream(
        url = content,
        mimeType = mimeType(this),
        codecs = codec,
        // averageBitrate is in kbit/s, bitrate in bit/s.
        bitrate = averageBitrate.positiveOrNull()?.times(KBIT) ?: bitrate.positiveOrNull(),
        languageTag = audioLocale?.toLanguageTag(),
        trackName = audioTrackName,
        isOriginal = audioTrackType == null || audioTrackType == AudioTrackType.ORIGINAL,
        sampleRate = itagItem?.sampleRate?.positiveOrNull(),
        channels = itagItem?.audioChannels?.positiveOrNull(),
        segmentIndex = segmentIndex(initStart, initEnd, indexStart, indexEnd),
        contentLength = itagItem?.contentLength?.takeIf { it > 0 },
        httpHeaders = mediaHeaders(content),
    )
}

internal fun SubtitlesStream.toSubtitle(): Subtitle? {
    if (!isUrl) return null
    return Subtitle(
        url = content,
        mimeType = format?.mimeType ?: "text/vtt",
        languageTag = languageTag,
        isAutoGenerated = isAutoGenerated,
    )
}

internal fun StreamSegment.toChapter() =
    Chapter(
        title = title,
        start = Duration.ofSeconds(startTimeSeconds.toLong()),
        thumbnails = previewUrl?.let { listOf(Image(it, null, null)) }.orEmpty(),
    )
