package app.youtubely.core.model

import java.time.Duration
import java.time.Instant

/** Everything needed to play a video and render the watch screen. */
data class StreamInfo(
    val item: StreamItem,
    val description: String,
    val likeCount: Long?,
    val videoStreams: List<VideoStream>,
    val audioStreams: List<AudioStream>,
    /** Adaptive manifests; preferred over individual streams when present. */
    val dashManifestUrl: String?,
    val hlsManifestUrl: String?,
    val subtitles: List<Subtitle>,
    val chapters: List<Chapter>,
    val related: List<StreamItem>,
    /** Loudness relative to the YouTube reference level, used for volume normalization. */
    val loudnessDb: Float?,
    val publishedAt: Instant?,
)

data class VideoStream(
    val url: String,
    val mimeType: String,
    /** RFC 6381 codec string, e.g. `av01.0.08M.08` or `vp09.00.40.08`. */
    val codecs: String?,
    val width: Int,
    val height: Int,
    val fps: Int,
    val bitrate: Int?,
    val isHdr: Boolean,
    /** `true` for DASH video-only streams that must be merged with an [AudioStream]. */
    val isVideoOnly: Boolean,
)

data class AudioStream(
    val url: String,
    val mimeType: String,
    val codecs: String?,
    val bitrate: Int?,
    /** BCP 47 language tag of the track, `null` when there is a single unnamed track. */
    val languageTag: String?,
    val trackName: String?,
    val isOriginal: Boolean,
)

data class Subtitle(
    val url: String,
    val mimeType: String,
    val languageTag: String,
    val isAutoGenerated: Boolean,
)

data class Chapter(
    val title: String,
    val start: Duration,
    val thumbnails: List<Image>,
)
