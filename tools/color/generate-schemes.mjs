// Generates the fallback color schemes used when Dynamic Color is unavailable (API < 31)
// or turned off by the user. Run from this directory:
//
//   npm ci && npm run generate
//
// The output file is checked in; regenerate it whenever SEED or the library version changes.
import { writeFileSync } from 'node:fs';
import { register } from 'node:module';
import { fileURLToPath } from 'node:url';

// material-color-utilities 0.4.0 ships one extensionless relative import
// (scheme/*.js -> '../dynamiccolor/dynamic_scheme'), which Node's ESM resolver rejects.
// This hook appends '.js' to such imports inside the package only.
register('data:text/javascript,' + encodeURIComponent(`
  export async function resolve(specifier, context, next) {
    if (context.parentURL?.includes('/@material/material-color-utilities/')
        && specifier.startsWith('.') && !specifier.endsWith('.js')) {
      return next(specifier + '.js', context);
    }
    return next(specifier, context);
  }
`));
const { Hct, SchemeTonalSpot } = await import('@material/material-color-utilities');

const SEED = 0xff7c4dff;
const SPEC = '2025';
const OUTPUT = fileURLToPath(new URL(
  '../../core/designsystem/src/main/kotlin/app/youtubely/core/designsystem/theme/SeedColorSchemes.kt',
  import.meta.url,
));

// Names match the parameters of androidx.compose.material3.lightColorScheme/darkColorScheme.
const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceTint', 'inverseSurface', 'inverseOnSurface',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'outline', 'outlineVariant', 'scrim',
  'surfaceBright', 'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
  'surfaceContainerLow', 'surfaceContainerLowest', 'surfaceDim',
  'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed', 'onPrimaryFixedVariant',
  'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed', 'onSecondaryFixedVariant',
  'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant',
];

const VARIANTS = [
  { name: 'seedLightColorScheme', fn: 'lightColorScheme', dark: false, contrast: 0.0 },
  { name: 'seedDarkColorScheme', fn: 'darkColorScheme', dark: true, contrast: 0.0 },
  { name: 'seedLightHighContrastColorScheme', fn: 'lightColorScheme', dark: false, contrast: 1.0 },
  { name: 'seedDarkHighContrastColorScheme', fn: 'darkColorScheme', dark: true, contrast: 1.0 },
];

const hex = (argb) => '0x' + (argb >>> 0).toString(16).toUpperCase().padStart(8, '0');

const blocks = VARIANTS.map(({ name, fn, dark, contrast }) => {
  const scheme = new SchemeTonalSpot(Hct.fromInt(SEED), dark, contrast, SPEC);
  const args = ROLES.map((role) => `        ${role} = Color(${hex(scheme[role])}),`).join('\n');
  // Formatted the way ktlint (spotless) wants it, so regenerating produces no diff.
  return `internal val ${name} =\n    ${fn}(\n${args}\n    )`;
});

const header = `// SPDX-FileCopyrightText: 2026 YouTubely contributors
// SPDX-License-Identifier: GPL-3.0-or-later
package app.youtubely.core.designsystem.theme

import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

// Generated by tools/color/generate-schemes.mjs — do not edit by hand.
// Seed ${hex(SEED)}, SchemeTonalSpot, spec ${SPEC}.
`;

writeFileSync(OUTPUT, header + '\n' + blocks.join('\n\n') + '\n');
console.log(`Wrote ${OUTPUT}`);
